export const DICTIONARY_SET = new Set([
  ...WORDS_4,
  ...WORDS_5,
])

/**
 * Check if word exists in the dictionary in O(1) time
 */
export function isValidWord(word) {
  if (!word || typeof word !== 'string') return false
  return DICTIONARY_SET.has(word.trim().toUpperCase())
}

/**
 * Count letter differences between two same-length words
 */
export function countLetterDifferences(a, b) {
  if (!a || !b || a.length !== b.length) return 999
  const uA = a.toUpperCase()
  const uB = b.toUpperCase()
  let diff = 0
  for (let i = 0; i < uA.length; i++) {
    if (uA[i] !== uB[i]) diff++
  }
  return diff
}

/**
 * Returns the 0-based index of the single changed letter (or -1 if identical/multiple)
 */
export function getDiffIndex(a, b) {
  if (!a || !b || a.length !== b.length) return -1
  const uA = a.toUpperCase()
  const uB = b.toUpperCase()
  let diffIdx = -1
  let diffCount = 0
  for (let i = 0; i < uA.length; i++) {
    if (uA[i] !== uB[i]) {
      diffIdx = i
      diffCount++
    }
  }
  return diffCount === 1 ? diffIdx : -1
}
